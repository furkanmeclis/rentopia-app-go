// listRow mirrors db.GetFieldTaskRow field by field; GetFieldTask and
// ListFieldTasks (queries/field_tasks.sql) select the same columns, and the
// compiler catches a column added to one but not the other.

package usecase

import "github.com/furkanmeclis/nextjs-go-boilerplate/backend/internal/database/db"

// listRow converts a list row into the detail row the view reads.
func listRow(r db.ListFieldTasksRow) db.GetFieldTaskRow {
	return db.GetFieldTaskRow{
		ID:                   r.ID,
		Uuid:                 r.Uuid,
		TaskType:             r.TaskType,
		Status:               r.Status,
		Origin:               r.Origin,
		BranchID:             r.BranchID,
		DueAt:                r.DueAt,
		PlannedMinutes:       r.PlannedMinutes,
		Note:                 r.Note,
		StartedAt:            r.StartedAt,
		CompletedAt:          r.CompletedAt,
		CompletionNote:       r.CompletionNote,
		AssignedAt:           r.AssignedAt,
		IssueNote:            r.IssueNote,
		IssueReportedAt:      r.IssueReportedAt,
		LocationKind:         r.LocationKind,
		Address:              r.Address,
		District:             r.District,
		City:                 r.City,
		Latitude:             r.Latitude,
		Longitude:            r.Longitude,
		ContactName:          r.ContactName,
		ContactPhone:         r.ContactPhone,
		FlightNumber:         r.FlightNumber,
		MeetingNote:          r.MeetingNote,
		CreatedAt:            r.CreatedAt,
		UpdatedAt:            r.UpdatedAt,
		RentalID:             r.RentalID,
		ReservationID:        r.ReservationID,
		AssigneeID:           r.AssigneeID,
		ToBranchID:           r.ToBranchID,
		TransferID:           r.TransferID,
		BranchUuid:           r.BranchUuid,
		BranchCode:           r.BranchCode,
		BranchName:           r.BranchName,
		ToBranchUuid:         r.ToBranchUuid,
		ToBranchCode:         r.ToBranchCode,
		ToBranchName:         r.ToBranchName,
		PointUuid:            r.PointUuid,
		PointName:            r.PointName,
		PointType:            r.PointType,
		RentalUuid:           r.RentalUuid,
		RentalReference:      r.RentalReference,
		RentalStatus:         r.RentalStatus,
		ReservationUuid:      r.ReservationUuid,
		ReservationReference: r.ReservationReference,
		ReservationStatus:    r.ReservationStatus,
		ReservationStartsAt:  r.ReservationStartsAt,
		ReservationEndsAt:    r.ReservationEndsAt,
		VehicleUuid:          r.VehicleUuid,
		VehiclePlate:         r.VehiclePlate,
		ResolvedVehicleID:    r.ResolvedVehicleID,
		AssigneeUuid:         r.AssigneeUuid,
		AssigneeName:         r.AssigneeName,
		AssigneeSurname:      r.AssigneeSurname,
		AssigneeEmail:        r.AssigneeEmail,
		CompletedByUuid:      r.CompletedByUuid,
		CompletedByName:      r.CompletedByName,
		CompletedBySurname:   r.CompletedBySurname,
		CompletedByEmail:     r.CompletedByEmail,
		TransferUuid:         r.TransferUuid,
		TransferStatus:       r.TransferStatus,
		CustomerName:         r.CustomerName,
		CustomerPhone:        r.CustomerPhone,
	}
}
